#!/usr/bin/env python3
"""Regenerate or verify the profile tool counts in the published tables.

`crates/memnoth-mcp/npm/README.md` says these counts are "generated by
scripts/check_surface.py ... regenerated, not hand-written". This is that
script: the numbers come from `mn mcp exposes --json`, which reads
`TOOL_PROFILES`, and the table is rewritten in place from that answer.

Two ways to run it:

    python scripts/check_surface.py --write   # rewrite the table
    python scripts/check_surface.py           # verify, exit 1 when stale

The default is verify, because a check that silently rewrites the file it is
checking can never fail in CI — and a count drifting away from the table it
describes is exactly the bug this exists to catch.

Usage: check_surface.py [--write] [--binary PATH]
Exit: 0 when the table matches the table-driven counts, 1 when it does not.
"""

from __future__ import annotations

import argparse
import json
import os
import re
import subprocess
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
README = ROOT / "crates" / "memnoth-mcp" / "npm" / "README.md"

# `| `code` | 23 | Code-graph navigation plus the filesystem/git toolbox |`
ROW = re.compile(r"^\|\s*`(?P<profile>[a-z]+)`\s*\|\s*(?P<count>\d+)\s*\|(?P<rest>.*)\|\s*$")


def binary(explicit: str | None) -> Path:
    candidates = []
    if explicit:
        candidates.append(Path(explicit))
    for profile in ("debug", "release"):
        for name in ("mn", "mn.exe"):
            candidates.append(ROOT / "target" / profile / name)
    for candidate in candidates:
        if candidate.is_file() and os.access(candidate, os.X_OK):
            return candidate
    sys.exit(
        "no memnoth binary found — run `cargo build --bin mn`, "
        "or pass --binary"
    )


def counts(exe: Path) -> dict[str, int]:
    """Per-profile tool counts, as the server reports them."""
    result = subprocess.run(
        [str(exe), "mcp", "exposes", "--json"],
        capture_output=True,
        text=True,
        # A workspace of its own: `exposes` reads the registry, not a vault, and
        # running it in the repository must not create state on the way.
        cwd=str(ROOT),
    )
    if result.returncode != 0:
        sys.exit(f"`mcp exposes --json` failed: {result.stderr.strip()}")
    text = result.stdout.strip()
    start = text.find("{")
    if start < 0:
        sys.exit(f"`mcp exposes --json` printed no JSON: {text[:200]}")
    data = json.loads(text[start:])
    profiles = data.get("profiles") or data.get("data", {}).get("profiles") or []
    if not profiles:
        sys.exit("`mcp exposes --json` reported no profiles")
    return {row["profile"]: row["tool_count"] for row in profiles}


def main() -> int:
    parser = argparse.ArgumentParser()
    parser.add_argument("--write", action="store_true", help="rewrite the table")
    parser.add_argument("--binary", help="path to mn")
    args = parser.parse_args()

    live = counts(binary(args.binary))
    original = README.read_text(encoding="utf-8")
    lines = original.splitlines()
    changed: list[str] = []
    seen: set[str] = set()

    for index, line in enumerate(lines):
        match = ROW.match(line)
        if not match:
            continue
        profile = match.group("profile")
        if profile not in live:
            continue
        seen.add(profile)
        want = live[profile]
        if int(match.group("count")) != want:
            lines[index] = f"| `{profile}` | {want} |{match.group('rest')}|"
            changed.append(f"{profile}: {match.group('count')} -> {want}")

    missing = sorted(set(live) - seen)
    stale = [f"{row} is not in {README.relative_to(ROOT)}" for row in missing]

    if not changed and not stale:
        print("surface: every published count matches TOOL_PROFILES")
        return 0

    for line in changed + stale:
        print(f"surface: {line}")

    if not args.write:
        print("\nsurface: the published table is stale — run with --write", file=sys.stderr)
        return 1

    body = "\n".join(lines)
    if original.endswith("\n"):
        body += "\n"
    README.write_text(body, encoding="utf-8")
    print(f"\nsurface: rewrote {README.relative_to(ROOT)}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
