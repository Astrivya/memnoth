//! Automation commands: hooks, actions, CI integration.

use anyhow::{Context, Result};
use serde_json::json;
use std::fs;

use crate::cli::{
    ActionArgs, ActionCommand, ActionInitArgs, CiArgs, CiCommand, CiDetectArgs, CiIndexArgs,
    HookArgs, HookCommand, HookInstallArgs,
};
use crate::context::AppContext;
use crate::output::Outcome;

/// Run the automation command.
pub fn run(ctx: &AppContext, args: &crate::cli::AutomationArgs) -> Result<Outcome> {
    match &args.action {
        crate::cli::AutomationCommand::Hook(args) => hook(ctx, args),
        crate::cli::AutomationCommand::Action(args) => action(ctx, args),
        crate::cli::AutomationCommand::Ci(args) => ci(ctx, args),
    }
}

/// `mn hooks install` — install pre-commit hook for kg index.
fn hook(ctx: &AppContext, args: &HookArgs) -> Result<Outcome> {
    match &args.action {
        HookCommand::Install(args) => hook_install(ctx, args),
    }
}

/// `mn action init` — generate GitHub Action workflow for CI.
fn action(ctx: &AppContext, args: &ActionArgs) -> Result<Outcome> {
    match &args.action {
        ActionCommand::Init(args) => action_init(ctx, args),
    }
}

/// `mn ci detect` — detect CI environment.
/// `mn ci index` — index in CI.
fn ci(ctx: &AppContext, args: &CiArgs) -> Result<Outcome> {
    match &args.action {
        CiCommand::Detect(args) => ci_detect(ctx, args),
        CiCommand::Index(args) => ci_index(ctx, args),
    }
}

/// Generate pre-commit hook content for kg index.
fn pre_commit_hook_content() -> String {
    r#"#!/bin/sh
# memnoth pre-commit hook
# This hook runs `mn kg index` before each commit to keep the code graph up to date.
# To skip: git commit --no-verify

# Pre-commit hook for memnoth code graph indexing

# Check if memnoth is available
if ! command -v mn >/dev/null 2>&1; then
    echo "memnoth (mn) not found in PATH, skipping kg index"
    exit 0
fi

# Check if we're in a git repository
if ! git rev-parse --git-dir >/dev/null 2>&1; then
    echo "Not in a git repository, skipping kg index"
    exit 0
fi

# Run kg index (quiet mode to avoid noise in commit output)
echo "Running memnoth kg index..."
if ! mn kg index --quiet 2>/dev/null; then
    echo "Warning: mn kg index failed (non-blocking)"
    # Don't fail the commit on index failure - just warn
fi

exit 0
"#
    .to_string()
}

/// Generate the post-commit hook that writes the change receipt.
///
/// Post-commit, not pre-commit: a receipt names a commit id, and that id does
/// not exist until the commit succeeds. A receipt written before the commit
/// would describe one that might never happen.
fn post_commit_hook_content() -> String {
    r#"#!/bin/sh
# memnoth post-commit hook
# Writes the mn-receipt/1 document for the commit that just landed.
# Non-blocking: a receipt is evidence, not a gate on committing.

if ! command -v mn >/dev/null 2>&1; then
    exit 0
fi

mn receipt write >/dev/null 2>&1 || echo "memnoth: receipt not written (non-blocking)"
exit 0
"#
    .to_string()
}

/// Generate .pre-commit-hooks.yaml for pre-commit framework.
fn pre_commit_hooks_yaml() -> String {
    r#"# memnoth pre-commit hooks configuration
# Install with: pre-commit install
# Run manually: pre-commit run --all-files

repos:
  - repo: local
    hooks:
      - id: memnoth-kg-index
        name: memnoth kg index
        entry: mn kg index --quiet
        language: system
        types: [rust, python, javascript, typescript, go, java, cpp, c]
        pass_filenames: false
        always_run: false
        description: "Update memnoth code graph index"
"#
    .to_string()
}

/// Generate GitHub Actions workflow for memnoth CI integration.
fn github_actions_workflow(project_name: &str, run_kg_index: bool, run_sync: bool) -> String {
    let mut steps = vec![
        r#"      - name: Checkout repository
        uses: actions/checkout@v4
        with:
          fetch-depth: 0"#,
    ];

    if run_kg_index {
        steps.push(
            r#"      - name: Install memnoth
        run: |
          curl -fsSL https://memnoth.astrivya.ai/install.sh | sh
          echo "$HOME/.memnoth/bin" >> $GITHUB_PATH
      - name: Build code graph index
        run: mn kg index --quiet
        env:
          MEMNOTH_API_KEY: ${{ secrets.MEMNOTH_API_KEY }}"#,
        );
    }

    if run_sync {
        steps.push(
            r#"      - name: Sync to memnoth cloud
        run: mn cloud sync
        env:
          MEMNOTH_API_KEY: ${{ secrets.MEMNOTH_API_KEY }}"#,
        );
    }

    format!(
        r#"# memnoth CI workflow
# Generated by `mn action init`
# Add MEMNOTH_API_KEY to GitHub repository secrets

name: memnoth CI

on:
  push:
    branches: [main, master]
  pull_request:
    branches: [main, master]

permissions:
  contents: read

jobs:
  memnoth:
    name: memnoth ({})
    runs-on: ubuntu-latest
    steps:
{}
"#,
        project_name,
        steps.join("\n")
    )
}

/// `mn hooks install` — install pre-commit hook for kg index.
fn hook_install(ctx: &AppContext, args: &HookInstallArgs) -> Result<Outcome> {
    let root = &ctx.root;
    let git_dir = root.join(".git");
    let hooks_dir = git_dir.join("hooks");
    let pre_commit_path = hooks_dir.join("pre-commit");

    // Check if we're in a git repo
    if !git_dir.exists() {
        return Err(anyhow::anyhow!(
            "Not a git repository (no .git directory found)"
        ));
    }

    // Create hooks directory if needed
    fs::create_dir_all(&hooks_dir).context("Failed to create .git/hooks directory")?;

    let hook_content = pre_commit_hook_content();

    // Check if hook already exists
    if pre_commit_path.exists() {
        let existing = fs::read_to_string(&pre_commit_path)
            .context("Failed to read existing pre-commit hook")?;

        if existing.contains("memnoth kg index") && !args.force {
            let text =
                "Pre-commit hook already contains memnoth kg index. Use --force to overwrite.";
            let data = json!({
                "installed": false,
                "reason": "already_exists",
                "path": pre_commit_path.display().to_string(),
            });
            return Ok(Outcome::new("hooks.install", text, data));
        }

        if !args.force {
            // Backup existing hook
            let backup_path = pre_commit_path.with_extension("pre-commit.backup");
            fs::copy(&pre_commit_path, &backup_path)
                .context("Failed to backup existing pre-commit hook")?;
        }
    }

    // Write the hook
    fs::write(&pre_commit_path, hook_content).context("Failed to write pre-commit hook")?;

    // Make executable
    #[cfg(unix)]
    {
        use std::os::unix::fs::PermissionsExt;
        let mut perms = fs::metadata(&pre_commit_path)?.permissions();
        perms.set_mode(0o755);
        fs::set_permissions(&pre_commit_path, perms)?;
    }

    // The receipt needs the commit id, so it is written after the commit.
    let post_commit_path = hooks_dir.join("post-commit");
    let install_post = !post_commit_path.exists()
        || args.force
        || fs::read_to_string(&post_commit_path)
            .map(|text| text.contains("memnoth post-commit hook"))
            .unwrap_or(false);
    if install_post {
        fs::write(&post_commit_path, post_commit_hook_content())
            .context("Failed to write post-commit hook")?;
        #[cfg(unix)]
        {
            use std::os::unix::fs::PermissionsExt;
            let mut perms = fs::metadata(&post_commit_path)?.permissions();
            perms.set_mode(0o755);
            fs::set_permissions(&post_commit_path, perms)?;
        }
    }

    // Also write .pre-commit-hooks.yaml for pre-commit framework
    let hooks_yaml_path = root.join(".pre-commit-hooks.yaml");
    if !hooks_yaml_path.exists() || args.force {
        fs::write(&hooks_yaml_path, pre_commit_hooks_yaml())
            .context("Failed to write .pre-commit-hooks.yaml")?;
    }

    let text = format!(
        "Installed pre-commit hook at {}\nInstalled post-commit receipt hook at {}\nAlso wrote .pre-commit-hooks.yaml for pre-commit framework",
        pre_commit_path.display(),
        post_commit_path.display()
    );

    let data = json!({
        "installed": true,
        "hook_path": pre_commit_path.display().to_string(),
        "receipt_hook_path": post_commit_path.display().to_string(),
        "hooks_yaml_path": hooks_yaml_path.display().to_string(),
    });

    Ok(Outcome::new("hooks.install", text, data))
}

/// `mn action init` — generate GitHub Action workflow for CI.
fn action_init(ctx: &AppContext, args: &ActionInitArgs) -> Result<Outcome> {
    let root = &ctx.root;
    let workflows_dir = root.join(".github").join("workflows");
    let workflow_path = workflows_dir.join("memnoth.yml");

    // Determine project name
    let project_name = args.name.clone().unwrap_or_else(|| {
        root.file_name()
            .and_then(|n| n.to_str())
            .unwrap_or("memnoth-project")
            .to_string()
    });

    fs::create_dir_all(&workflows_dir).context("Failed to create .github/workflows directory")?;

    let workflow_content = github_actions_workflow(&project_name, args.kg_index, args.sync);

    // Check if workflow already exists
    if workflow_path.exists() && !args.force {
        let text = format!(
            "Workflow already exists at {}. Use --force to overwrite.",
            workflow_path.display()
        );
        let data = json!({
            "created": false,
            "reason": "already_exists",
            "path": workflow_path.display().to_string(),
        });
        return Ok(Outcome::new("action.init", text, data));
    }

    fs::write(&workflow_path, workflow_content)
        .context("Failed to write GitHub Actions workflow")?;

    let text = format!(
        "Created GitHub Actions workflow at {}\n\nNext steps:\n1. Add MEMNOTH_API_KEY to your GitHub repository secrets\n2. Push to trigger the workflow",
        workflow_path.display()
    );

    let data = json!({
        "created": true,
        "path": workflow_path.display().to_string(),
        "project_name": project_name,
        "kg_index": args.kg_index,
        "sync": args.sync,
    });

    Ok(Outcome::new("action.init", text, data))
}

/// `mn ci detect` — detect CI environment.
fn ci_detect(_ctx: &AppContext, _args: &CiDetectArgs) -> Result<Outcome> {
    let mut detected = Vec::new();
    let mut ci_name = "unknown";

    // Check common CI environment variables
    if std::env::var("GITHUB_ACTIONS").is_ok() {
        detected.push("github_actions");
        ci_name = "GitHub Actions";
    }
    if std::env::var("GITLAB_CI").is_ok() {
        detected.push("gitlab_ci");
        ci_name = "GitLab CI";
    }
    if std::env::var("CI").is_ok() {
        detected.push("generic_ci");
        if ci_name == "unknown" {
            ci_name = "Generic CI";
        }
    }
    if std::env::var("BUILDKITE").is_ok() {
        detected.push("buildkite");
        ci_name = "Buildkite";
    }
    if std::env::var("CIRCLECI").is_ok() {
        detected.push("circleci");
        ci_name = "CircleCI";
    }
    if std::env::var("TRAVIS").is_ok() {
        detected.push("travis");
        ci_name = "Travis CI";
    }
    if std::env::var("APPVEYOR").is_ok() {
        detected.push("appveyor");
        ci_name = "AppVeyor";
    }
    if std::env::var("TEAMCITY_VERSION").is_ok() {
        detected.push("teamcity");
        ci_name = "TeamCity";
    }
    if std::env::var("BITBUCKET_BUILD_NUMBER").is_ok() {
        detected.push("bitbucket");
        ci_name = "Bitbucket Pipelines";
    }
    if std::env::var("AZURE_HTTP_USER_AGENT").is_ok() {
        detected.push("azure_devops");
        ci_name = "Azure DevOps";
    }

    let is_ci = !detected.is_empty();

    let text = if is_ci {
        format!(
            "CI environment detected: {} ({})",
            ci_name,
            detected.join(", ")
        )
    } else {
        "No CI environment detected".to_string()
    };

    let data = json!({
        "is_ci": is_ci,
        "ci_name": ci_name,
        "detected": detected,
    });

    Ok(Outcome::new("ci.detect", text, data))
}

/// `mn ci index` — index in CI.
fn ci_index(ctx: &AppContext, args: &CiIndexArgs) -> Result<Outcome> {
    // First detect CI environment
    let detect_args = CiDetectArgs { json: ctx.json };
    let detect_result = ci_detect(ctx, &detect_args)?;

    let is_ci = detect_result.data["is_ci"].as_bool().unwrap_or(false);

    if !is_ci && !args.force {
        let text = "Not running in CI environment. Use --force to run anyway.";
        let data = json!({
            "indexed": false,
            "reason": "not_in_ci",
            "ci_info": detect_result.data,
        });
        return Ok(Outcome::new("ci.index", text, data));
    }

    // Run kg index
    let kg_args = crate::cli::KgArgs {
        action: crate::cli::KgCommand::Index {
            full: args.full,
            no_embed: args.no_embed,
        },
    };

    let kg_result = crate::commands::execute(ctx, &crate::cli::Verb::Kg(kg_args))
        .map_err(|e| anyhow::anyhow!("{e}"))?;

    // If sync is requested and we have cloud credentials, run cloud sync
    let mut sync_result = None;
    if args.sync {
        let sync_args = crate::cli::SyncArgs {
            dry_run: false,
            watch: false,
            json: ctx.json,
        };
        if let Ok(result) = crate::sync::run_sync(ctx, &sync_args) {
            sync_result = Some(result.data);
        }
    }
    let text = if is_ci {
        format!(
            "CI index completed in {} environment",
            detect_result.data["ci_name"].as_str().unwrap_or("unknown")
        )
    } else {
        "Index completed (forced outside CI)".to_string()
    };

    let mut data = json!({
        "indexed": true,
        "ci_info": detect_result.data,
        "kg_result": kg_result.data,
    });

    if let Some(sync_data) = sync_result {
        data["sync_result"] = sync_data;
    }

    Ok(Outcome::new("ci.index", text, data))
}
